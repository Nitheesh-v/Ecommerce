"use client";

import { Download, Loader2, Users } from "lucide-react";
import { useState } from "react";
import { Button } from "@/components/admin/ui/button";
import { Card } from "@/components/admin/ui/card";
import { PageHeader } from "@/components/admin/ui/page-header";
import { Pagination } from "@/components/admin/ui/pagination";
import { EmptyState, ErrorState } from "@/components/admin/ui/states";
import { useCustomerAnalytics, useCustomerList } from "@/hooks/use-customer-list";
import { getApiErrorMessage } from "@/lib/api/errors";
import { customersService } from "@/services/admin/customers.service";
import { toast } from "@/store/toast.store";
import type { CustomerSortField } from "@/types/customer";
import { CustomersFiltersBar } from "./customers-filters";
import { CustomersTable } from "./customers-table";
import { CustomerSummaryCards } from "./customer-summary-cards";

export function CustomersView() {
  const {
    filters,
    query,
    update,
    reset,
    refresh,
    items,
    meta,
    error,
    loading,
    hasActiveFilters,
  } = useCustomerList();
  const analytics = useCustomerAnalytics();
  const [exporting, setExporting] = useState(false);

  const onSort = (field: CustomerSortField) => {
    update({
      sortBy: field,
      sortOrder:
        filters.sortBy === field && filters.sortOrder === "desc" ? "asc" : "desc",
    });
  };

  /**
   * The CSV is generated by the API with the same filters as the table, so what an
   * operator sees is exactly what they export.
   */
  const onExport = async () => {
    setExporting(true);

    try {
      const filename = await customersService.exportCsv({
        search: query.search,
        status: query.status,
        from: query.from,
        to: query.to,
        minSpent: query.minSpent,
        maxSpent: query.maxSpent,
        hasOrders: query.hasOrders,
        sortBy: query.sortBy,
        sortOrder: query.sortOrder,
      });

      toast.success(`Downloaded ${filename}`);
    } catch (error_) {
      toast.error(getApiErrorMessage(error_));
    } finally {
      setExporting(false);
    }
  };

  return (
    <div className="space-y-5">
      <PageHeader
        title="Customers"
        description="Every registered customer, their spending and account state."
        actions={
          <div className="flex items-center gap-2">
            <Button variant="secondary" onClick={onExport} disabled={exporting}>
              {exporting ? (
                <Loader2 className="h-4 w-4 animate-spin" aria-hidden />
              ) : (
                <Download className="h-4 w-4" aria-hidden />
              )}
              Export CSV
            </Button>
            <Button variant="secondary" onClick={refresh}>
              Refresh
            </Button>
          </div>
        }
      />

      {analytics.error ? (
        <ErrorState message={analytics.error} onRetry={analytics.refresh} />
      ) : (
        <CustomerSummaryCards
          overview={analytics.overview}
          loading={analytics.loading}
        />
      )}

      {error ? <ErrorState message={error} onRetry={refresh} /> : null}

      <Card className="overflow-hidden">
        <CustomersFiltersBar
          filters={filters}
          onChange={update}
          onReset={reset}
          hasActiveFilters={hasActiveFilters}
          total={meta?.total ?? 0}
        />

        {!loading && items.length === 0 && meta !== null ? (
          <div className="p-5">
            <EmptyState
              icon={Users}
              title={hasActiveFilters ? "No customers match these filters" : "No customers yet"}
              description={
                hasActiveFilters
                  ? "Try a different search term, status or date range."
                  : "Customers appear here as soon as they register or place an order."
              }
              action={
                hasActiveFilters ? (
                  <Button variant="secondary" size="sm" onClick={reset} className="mt-2">
                    Clear filters
                  </Button>
                ) : undefined
              }
            />
          </div>
        ) : (
          <CustomersTable
            items={items}
            loading={loading}
            sortBy={filters.sortBy}
            sortOrder={filters.sortOrder}
            onSort={onSort}
          />
        )}

        {meta ? (
          <Pagination
            meta={meta}
            onPageChange={(page) => update({ page })}
            disabled={loading}
          />
        ) : null}
      </Card>
    </div>
  );
}
